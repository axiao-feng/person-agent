import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export type LauncherInstallResult = {
  exePath: string;
  configPath: string;
  nodePath: string;
  cliPath: string;
  desktopShortcut: string;
  startMenuShortcut: string;
};

export type LauncherInstallOptions = {
  projectRoot?: string;
  nodePath?: string;
  cliPath?: string;
  createShortcuts?: boolean;
};

export function installLauncher(options: LauncherInstallOptions = {}): LauncherInstallResult {
  requireWindows();
  const root = options.projectRoot ?? findProjectRoot();
  const source = join(root, "launcher", "PersonAgent.cs");
  if (!existsSync(source)) throw new Error(`找不到启动器源码：${source}`);
  const cliPath = options.cliPath ?? join(root, "dist", "src", "cli.js");
  if (!existsSync(cliPath)) throw new Error("找不到 dist/src/cli.js，请先运行 pnpm build。");
  const nodePath = options.nodePath ?? process.execPath;
  if (!existsSync(nodePath)) throw new Error(`找不到 Node.js：${nodePath}`);
  const outputDirectory = join(root, "launcher", "bin");
  mkdirSync(outputDirectory, { recursive: true });
  const exePath = join(outputDirectory, "PersonAgent.exe");
  const csc = findCSharpCompiler();
  const compilation = spawnSync(
    csc,
    [
      "/nologo",
      "/target:winexe",
      "/optimize+",
      "/codepage:65001",
      "/r:System.Windows.Forms.dll",
      "/r:System.Drawing.dll",
      `/out:${exePath}`,
      source,
    ],
    { encoding: "utf8", windowsHide: true },
  );
  if (compilation.status !== 0) {
    throw new Error(
      `C# 启动器编译失败。\n${(compilation.stderr || compilation.stdout || "").trim()}`.trim(),
    );
  }
  if (!existsSync(exePath)) throw new Error("C# 启动器编译完成但找不到 PersonAgent.exe。");
  const configPath = join(outputDirectory, "launcher.ini");
  writeFileSync(
    configPath,
    `; generated by person-agent launcher install\n${launcherIni(nodePath, cliPath)}`,
    "utf8",
  );

  let desktopShortcut = "";
  let startMenuShortcut = "";
  if (options.createShortcuts !== false) {
    const script = shortcutScript(exePath, root);
    const encoded = Buffer.from(script, "utf16le").toString("base64");
    const result = spawnSync("powershell.exe", ["-NoProfile", "-NonInteractive", "-EncodedCommand", encoded], {
      encoding: "utf8",
      windowsHide: true,
    });
    if (result.status !== 0) {
      throw new Error((result.stderr || result.stdout || "创建快捷方式失败。").trim());
    }
    const lines = result.stdout
      .split(/\r?\n/)
      .map((line) => line.trim())
      .filter(Boolean);
    desktopShortcut = lines.at(-2) ?? join(desktopDirectory(), "Person Agent.lnk");
    startMenuShortcut = lines.at(-1) ?? join(programsDirectory(), "Person Agent.lnk");
  }
  return { exePath, configPath, nodePath, cliPath, desktopShortcut, startMenuShortcut };
}

export function launcherIni(nodePath: string, cliPath: string): string {
  return [`node=${nodePath}`, `cli=${cliPath}`, ""].join("\n");
}

export function findCSharpCompiler(): string {
  const windows = process.env.WINDIR || process.env.SystemRoot || "C:\\Windows";
  const candidates = [
    join(windows, "Microsoft.NET", "Framework64", "v4.0.30319", "csc.exe"),
    join(windows, "Microsoft.NET", "Framework", "v4.0.30319", "csc.exe"),
  ];
  const compiler = candidates.find((candidate) => existsSync(candidate));
  if (!compiler) throw new Error("找不到系统自带的 C# 编译器（.NET Framework csc.exe）。");
  return compiler;
}

export function findProjectRoot(start = dirname(fileURLToPath(import.meta.url))): string {
  let directory = start;
  for (let depth = 0; depth < 8; depth += 1) {
    if (existsSync(join(directory, "package.json")) && existsSync(join(directory, "launcher", "PersonAgent.cs"))) {
      return directory;
    }
    const parent = dirname(directory);
    if (parent === directory) break;
    directory = parent;
  }
  throw new Error("找不到 person-agent 仓库根目录。");
}

function shortcutScript(exePath: string, root: string): string {
  const exe = escapePowerShell(exePath);
  const workingDirectory = escapePowerShell(root);
  return `
$ErrorActionPreference = 'Stop'
$ws = New-Object -ComObject WScript.Shell
$desktopLink = Join-Path ([Environment]::GetFolderPath('Desktop')) 'Person Agent.lnk'
$startLink = Join-Path ([Environment]::GetFolderPath('Programs')) 'Person Agent.lnk'
$desktop = $ws.CreateShortcut($desktopLink)
$desktop.TargetPath = '${exe}'
$desktop.WorkingDirectory = '${workingDirectory}'
$desktop.Description = 'Person Agent 知识录入'
$desktop.Save()
$startMenu = $ws.CreateShortcut($startLink)
$startMenu.TargetPath = '${exe}'
$startMenu.WorkingDirectory = '${workingDirectory}'
$startMenu.Description = 'Person Agent 知识录入'
$startMenu.Save()
Write-Output $desktopLink
Write-Output $startLink
`.trim();
}

function escapePowerShell(value: string): string {
  return value.replace(/'/g, "''");
}

function desktopDirectory(): string {
  return join(process.env.USERPROFILE || "", "Desktop");
}

function programsDirectory(): string {
  return join(
    process.env.APPDATA || "",
    "Microsoft",
    "Windows",
    "Start Menu",
    "Programs",
  );
}

function requireWindows(): void {
  if (process.platform !== "win32") throw new Error("桌面启动器安装仅支持 Windows。");
}
